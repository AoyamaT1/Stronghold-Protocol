def blank_skill(i, rec):
    base = f"{rec.get('charId') or rec.get('chessId')}"
    return {"skillId": f"skchr_limbus_{base}_{i+1}", "iconId": f"skchr_limbus_{base}_{i+1}",
            "name": "", "level": 7, "index": i, "isDefault": i == 0,
            "desc": "", "descRaw": "", "skillType": "MANUAL", "durationType": "NONE",
            "duration": 0, "spType": "INCREASE_WITH_TIME", "spCost": 0, "initSp": 0,
            "maxChargeTime": 1, "increment": 1, "bb": {}, "bbStr": {},
            "rangeId": None, "rangeGrid": None, "prefabId": None, "overrideTokenKey": None,
            "trigger": {"rule": "DEFAULT", "rawRule": "DEFAULT", "customRangeGrid": None}}


def main():
    c = json.load(open(PATH, encoding="utf-8"))
    n = 0
    for key, (trait, talents, skills) in S.items():
        for cid, rec in c.items():
            if key not in cid:
                continue
            rec["trait"] = {"desc": trait, "descRaw": trait, "bb": {}, "bbStr": {}, "rangeGrid": None}
            rec["talents"] = [{"index": i, "name": nm, "desc": d, "descRaw": d,
                               "bb": {}, "bbStr": {}, "rangeGrid": None,
                               "tokenKey": None, "hidden": False, "fromModule": False}
                              for i, (nm, d) in enumerate(talents)]
            if not rec.get("skills"):                # 辛克莱原本就没有技能数组
                rec["skills"] = [blank_skill(i, rec) for i in range(len(skills))]
            for i, sk in enumerate(rec["skills"]):
                if i >= len(skills):
                    continue
                nm, st, spt, sp, init, desc = skills[i]
                if st == "AUTO" and not sp:
                    sp = 7                           # AUTO 也要技力，给个合理值
                sk.update({"name": nm, "desc": desc, "descRaw": desc,
                           "skillType": st, "spType": spt, "spCost": sp, "initSp": init,
                           "durationType": "NONE", "duration": 0,
                           "maxChargeTime": 1, "increment": 1,
                           "trigger": sk.get("trigger") or
                           {"rule": "DEFAULT", "rawRule": "DEFAULT", "customRangeGrid": None}})
            if not any(s.get("isDefault") for s in rec["skills"]):
                rec["skills"][0]["isDefault"] = True
            rec["skill"] = dict(next(s for s in rec["skills"] if s.get("isDefault")))
            n += 1
    json.dump(c, open(PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"已重写 {n} 条记录的技能（{len(S)} 个罪人）")


if __name__ == "__main__":
    main()
